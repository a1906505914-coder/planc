# 泰国主体判断
def is_thai_entity(entity_name):
    """按实体名判断是否泰国账套（实体名含 泰国/THAI）。"""
    if not entity_name:
        return False
    s = str(entity_name)
    return any(k in s for k in THAI_ENTITY_KWS)


def thai_code_to_std(code):
    """泰国代码（可能带点/子目）→ 集团标准一级代码；无映射返回原代码。"""
    if not code:
        return code
    cn = str(code).split('.')[0].strip()
    return THAI_CODE_MAP.get(cn, code)


