def normalize_thai_tb(tb, entities):
    """对泰国主体的 TB 行做名称/代码归一化（2026-08-01 修复 Z 泰国账套）。
    泰国科目名（如 应收账款和应收票据/预付费用）与集团标准名（应收账款/预付账款）不同，
    泰国代码（1130/1151）与集团标准代码（1122/1123）不同 → 集团 builder 按标准名/码取不到。

    策略：对泰国主体，将其 TB 行【复制一份】映射到集团标准名+标准码（保留原行不影响其他逻辑）：
      · 名称映射：THAI_NAME_TO_STD（含"应收账款和应收票据"→"应收账款"等）；
      · 代码映射：泰国一级代码→集团标准一级代码（1130→1122 等），子目代码同步替换前缀；
      · 特殊子目：1130.04 其他应收款 → 1221（其他应收款）；2120.03 其他应付账款 → 2241。
    返回新的 tb dict（含泰国归一化行），不修改原 tb。
    """
    import copy as _copy
    out = dict(tb)
    thai_ents = {e for e in entities if is_thai_entity(e)}
    if not thai_ents:
        return out
    # 子目级特殊映射（优先于一级前缀）：泰国子目代码 → (集团标准码, 集团标准名)
    _SUB_SPECIAL = {
        '1130.04': ('1221', '其他应收款'),
        '2120.03': ('2241', '其他应付款'),
        '1151.05': ('1221', '其他应收款'),   # 押金和担保 → 其他应收款
    }
    # 2026-08-02 修复双计：_SUB_SPECIAL 的【子目】须继承父级特殊映射，否则父级→1221/2241 而
    # 子目按一级前缀→1122/1123/2202（应收/预付/应付），同一笔金额同时出现在两个标准科目。
    # 例：泰国 TB 1130.04 其他应收款(1.89M) 有子目 1130.04.02~05；1151.05 押金和担保(8.57M)
    # 有子目 1151.05.01~03；2120.03 其他应付账款有子目 2120.03.01。修复后子目随父级映射
    # （1130.04.xx→1221.xx、1151.05.xx→1221.xx、2120.03.xx→2241.xx）。
    _SPECIAL_PREFIX = sorted(((k, v) for k, v in _SUB_SPECIAL.items()),
                             key=lambda kv: len(kv[0]), reverse=True)
    for (e, code, name, y), v in list(tb.items()):
        if e not in thai_ents:
            continue
        # 先按完整 code 精确匹配；再按「最长的特殊父级前缀」匹配（子目继承父级映射）
        _sub_hit = _SUB_SPECIAL.get(code)
        if _sub_hit is None:
            for _pk, _pv in _SPECIAL_PREFIX:   # 已按 key 长度降序，取最长匹配父级
                if str(code).startswith(_pk + '.'):
                    _sub_hit = _pv
                    break
        if _sub_hit:
            base_std, base_name = _sub_hit
            nname = base_name
            # 注意：1130.04 自身(含.04后缀)是「特殊子目」父级，其整级映射为标准一级 1221；
            # 其【更深子目】1130.04.02 才按 1221.02 映射（后缀接在 1221 之后，非 1130.04 之后）。
            if code in _SUB_SPECIAL:
                ncode = base_std                       # 特殊父级自身 → 标准一级（如 1130.04→1221）
            else:
                # 深子目：命中某特殊父级前缀，标准码 = 标准一级 + 剩余后缀（1130.04.02→1221.02）
                _pk = next((pk for pk, _ in _SPECIAL_PREFIX if str(code).startswith(pk + '.')), None)
                if _pk is not None:
                    ncode = base_std + str(code)[len(_pk):]
                else:
                    ncode = base_std
        else:
            nname = THAI_NAME_TO_STD.get(name, name)
            ncode = thai_code_to_std(code)
            if '.' in code:
                _p, _suf = str(code).split('.', 1)
                _std_p = thai_code_to_std(_p)
                ncode = f'{_std_p}.{_suf}' if _std_p != _p else code
        key = (e, ncode, nname, y)
        if key not in out:
            out[key] = dict(v)
        else:
            # 2026-08-02 修复：多个泰国子目映射到同一标准 key（如 1130.04 与 1151.05 均→1221
            # 其他应收款）时，旧逻辑直接丢弃后者→泰国其他应收款只剩 1.89M（1130.04），
            # 1151.05 押金 8.57M 丢失。改为金额累加（各字段自然相加）。
            _dst = out[key]
            for _k in ('qc', 'jf', 'df', 'qm'):
                _dst[_k] = _dst.get(_k, 0.0) + v.get(_k, 0.0)
    return out
